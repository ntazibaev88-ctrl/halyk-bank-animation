"""Trim narration clips and lay them out on the 130 s timeline.

Each chapter's lines are placed after a short lead-in, with even natural
pauses between sentences, ending before the chapter's closing transition.
Writes build/out/vo/*.wav and animation/timeline.js (used by the renderer).
"""
import json, os, subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VO = os.path.join(ROOT, "build", "out", "vo")
LEAD = 1.0        # seconds after chapter start before narration begins
TAIL = 0.9        # seconds of breathing room at chapter end
MIN_GAP, MAX_GAP = 0.7, 1.6


def trim(src, dst):
    f = ("silenceremove=start_periods=1:start_threshold=-45dB:start_silence=0.05,"
         "areverse,silenceremove=start_periods=1:start_threshold=-45dB:start_silence=0.12,areverse,"
         "afade=t=in:d=0.02")
    subprocess.run(["ffmpeg", "-y", "-v", "error", "-i", src, "-af", f, "-ar", "48000", "-ac", "1", dst], check=True)
    r = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", dst],
                       capture_output=True, text=True)
    return float(r.stdout)


script = json.load(open(os.path.join(ROOT, "script", "script.json")))
events = []
for ch in script["chapters"]:
    clips = []
    for i, line in enumerate(ch["lines"]):
        key = f"{ch['id']:02d}_{i}"
        d = trim(os.path.join(VO, key + ".mp3"), os.path.join(VO, key + ".wav"))
        clips.append((key, d, line))
    lead = ch.get("lead", LEAD)
    first = ch["lines"][0].get("at") or ch["start"] + lead
    room = ch["end"] - TAIL - first - sum(c[1] for c in clips)
    gaps = len(clips) - 1
    gap = min(MAX_GAP, room / gaps) if gaps else 0
    if gaps and gap < MIN_GAP:
        raise SystemExit(f"chapter {ch['id']} does not fit: gap {gap:.2f}s")
    t = first
    for key, d, line in clips:
        events.append({"key": key, "ch": ch["id"], "start": round(t, 3), "end": round(t + d, 3),
                       "kk": line["kk"], "en": line["en"]})
        print(f"ch{ch['id']} {t:7.2f} -> {t + d:7.2f}  {line['kk']}")
        t += d + gap

json.dump(events, open(os.path.join(ROOT, "build", "out", "vo_events.json"), "w"), ensure_ascii=False, indent=1)
chapters = [{k: c[k] for k in ("id", "start", "end", "title")} for c in script["chapters"]]
with open(os.path.join(ROOT, "animation", "timeline.js"), "w") as f:
    f.write("// Generated by build/timeline.py — do not edit by hand.\n")
    f.write("window.TIMELINE = " + json.dumps({"duration": script["duration"], "title": script["title"],
                                                "chapters": chapters, "lines": events},
                                               ensure_ascii=False, indent=1) + ";\n")
