"""Generate video/compositions/captions.html: short kinetic Russian subtitle groups
timed to the narration words in video/assets/timing.json; key words in yellow."""
import json, re, os
ROOT = os.path.dirname(os.path.abspath(__file__)) + "/.."
T = json.load(open(ROOT + "/video/assets/timing.json"))
KEY = {"сам", "решения", "мозг", "решил", "сотни", "автоматически", "короткий", "путь", "энергию", "шаблоны",
       "неловкий", "пятилетней", "сном", "снова", "неприятным", "воспоминаниям", "записывает", "реальность",
       "отбирает", "интерпретирует", "пробелы", "память", "видеозапись", "одно", "событие", "по-разному", "эмоции",
       "ожидания", "опыт", "точно", "помню", "верить", "хитрый", "обманщик", "голове", "замечал", "такое"}
MAXW, MAXC = 3, 17

def clean(w):  # keep ? ! and quotes, drop , . : ;
    return re.sub(r"[,.:;]", "", w).upper()

# Hand-phrased groups (short, natural breaks); each maps onto the narration words in order.
PHRASES = """Ты уверен, | что сам принимаешь | решения? | А что, если | твой мозг | уже всё решил | за тебя?
| Каждый день | ты принимаешь | сотни решений. | Но большинство | из них происходят | почти автоматически.
| Твой мозг постоянно | ищет короткий путь, | экономит энергию | и использует | привычные шаблоны.
| Замечал, | как неловкий момент | пятилетней давности | может всплыть | в голове | прямо перед сном?
| Мозг способен | снова и снова | возвращать тебя | к неприятным | воспоминаниям.
| Дело в том, | что мозг | не просто записывает | реальность. | Он отбирает | информацию, | интерпретирует её
| и заполняет пробелы. | Поэтому | твоя память — | не идеальная | видеозапись | прошлого.
| Два человека | могут пережить | одно и то же | событие, | но запомнить его | совершенно | по-разному.
| Потому что | на восприятие | влияют эмоции, | ожидания | и предыдущий опыт.
| Так что | в следующий раз, | когда твой мозг | скажет: | «Я точно | всё помню», | не спеши | ему верить.
| Иногда | самый хитрый | обманщик — | это тот, | кто живёт | у тебя в голове. | А ты замечал | за собой такое?"""
norm = lambda w: re.sub(r"[^а-яё\-]", "", w.lower().replace("ё", "е"))
words = T["words"]; wi = 0; groups = []
for ph in [p.strip() for p in PHRASES.replace("\n", " ").split("|")]:
    toks = [x for x in ph.split() if norm(x)]
    g = []
    for tk in toks:
        assert norm(words[wi]["text"]) == norm(tk), (tk, words[wi]["text"])
        g.append(words[wi]); wi += 1
    groups.append(g)
assert wi == len(words), "phrases do not cover the narration"

html, js = [], []
for i, g in enumerate(groups):
    start = round(g[0]["start"] - 0.06, 3)
    nxt = groups[i + 1][0]["start"] - 0.06 if i + 1 < len(groups) else 999
    end = round(min(nxt, g[-1]["end"] + 0.45), 3)
    dur = round(end - start, 3)
    label = " ".join(clean(w["text"]) for w in g)
    size = max(54, min(84, int(930 / (0.74 * max(8, len(label))))))
    spans = []
    for j, w in enumerate(g):
        k = re.sub(r"[^а-яё\-]", "", w["text"].lower()) in KEY
        spans.append(f'<span id="cap{i}-w{j}" class="w{" k" if k else ""}">{clean(w["text"])}</span>')
        js.append(f'tl.fromTo("#cap{i}-w{j}", {{ opacity: 0.45, y: 10 }}, {{ opacity: 1, y: 0, duration: 0.12, ease: "power2.out" }}, {round(w["start"], 3)});')
        if k: js.append(f'tl.fromTo("#cap{i}-w{j}", {{ scale: 1.25 }}, {{ scale: 1, duration: 0.28, ease: "back.out(3)" }}, {round(w["start"], 3)});')
    html.append(f'    <div id="cap{i}" class="clip cg" data-start="{start}" data-duration="{dur}"><div id="cap{i}-in" class="cin" style="font-size:{size}px">{" ".join(spans)}</div></div>')
    js.append(f'tl.fromTo("#cap{i}-in", {{ opacity: 0, scale: 0.8, y: 26 }}, {{ opacity: 1, scale: 1, y: 0, duration: 0.17, ease: "back.out(2.2)" }}, {start});')
    js.append(f'tl.to("#cap{i}-in", {{ opacity: 0, duration: 0.1, ease: "power2.in" }}, {round(end - 0.1, 3)});')

doc = f'''<template>
  <style>
    #root {{ position: absolute; inset: 0; pointer-events: none; }}
    .cg {{ position: absolute; left: 0; top: 1150px; width: 1080px; height: 190px; display: flex; align-items: center; justify-content: center; overflow: visible; }}
    .cin {{ display: inline-block; max-width: 1000px; text-align: center; font-family: BrainSans, sans-serif; font-weight: 900; line-height: 1.08; letter-spacing: 0.01em;
      color: #FFFDF6; padding: 10px 30px 14px; border-radius: 30px; background: rgba(7, 10, 31, 0.5);
      text-shadow: 4px 0 0 #0D0B26, -4px 0 0 #0D0B26, 0 4px 0 #0D0B26, 0 -4px 0 #0D0B26, 3px 3px 0 #0D0B26, -3px 3px 0 #0D0B26, 3px -3px 0 #0D0B26, -3px -3px 0 #0D0B26, 0 9px 0 rgba(13, 11, 38, 0.6); }}
    .w {{ display: inline-block; }}
    .w.k {{ color: #FFC93C; }}
  </style>
  <div id="root" data-composition-id="captions" data-width="1080" data-height="1920">
{chr(10).join(html)}
  </div>
  <script>
    (function () {{
      /* Generated by scripts/build_captions.py from assets/timing.json — edit the script, not this file. */
      const tl = gsap.timeline({{ paused: true }});
      {(chr(10) + "      ").join(js)}
      window.__timelines["captions"] = tl;
    }})();
  </script>
</template>
'''
open(ROOT + "/video/compositions/captions.html", "w").write(doc)
print(len(groups), "caption groups")
for g in groups: print(" ", round(g[0]["start"], 2), " ".join(clean(w["text"]) for w in g))

# Sidecar subtitles (sentence case, with punctuation) for upload to TikTok / YouTube.
def ts(x, sep=","):
    h, m = int(x // 3600), int(x % 3600 // 60); s = x % 60
    return f"{h:02d}:{m:02d}:{int(s):02d}{sep}{int(round((s - int(s)) * 1000)):03d}"
os.makedirs(ROOT + "/deliverables", exist_ok=True)
srt, vtt = [], ["WEBVTT", ""]
for i, g in enumerate(groups):
    a = g[0]["start"] - 0.06; b = min(groups[i + 1][0]["start"] - 0.06 if i + 1 < len(groups) else 99, g[-1]["end"] + 0.45)
    line = " ".join(w["text"] for w in g)
    srt += [str(i + 1), f"{ts(a)} --> {ts(b)}", line, ""]
    vtt += [f"{ts(a, '.')} --> {ts(b, '.')}", line, ""]
open(ROOT + "/deliverables/subtitles_ru.srt", "w").write("\n".join(srt))
open(ROOT + "/deliverables/subtitles_ru.vtt", "w").write("\n".join(vtt))
