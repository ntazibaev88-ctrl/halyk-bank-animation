"""Write video/lib/warp.js: per scene, anchor pairs [new_time, anim_time] (scene-local seconds)
so the animation, authored against timing_anim.json, hits each word of the current narration.
Also importable: old_to_new(scene, t) maps an authored beat to film time (used for SFX)."""
import json, os
import numpy as np
ROOT = os.path.dirname(os.path.abspath(__file__)) + "/.."
NEW = json.load(open(ROOT + "/video/assets/timing.json"))
OLD = json.load(open(ROOT + "/video/assets/timing_anim.json"))

def anchors():
    out = {}
    for sc in OLD["scenes"]:
        sid, s0, dur = sc["id"], sc["start"], sc["end"] - sc["start"]
        pairs = [(0.0, 0.0)]
        ow = [w for w in OLD["words"] if w["scene"] == sid]; nw = [w for w in NEW["words"] if w["scene"] == sid]
        assert len(ow) == len(nw)
        for o, n in zip(ow, nw): pairs.append((n["start"] - s0, o["start"] - s0))
        oc = [c for c in OLD["clauses"] if c["scene"] == sid]; nc = [c for c in NEW["clauses"] if c["scene"] == sid]
        for o, n in zip(oc, nc): pairs.append((n["end"] - s0, o["end"] - s0))
        pairs.append((dur, dur))
        pairs.sort()
        clean = [pairs[0]]
        for a, b in pairs[1:]:  # keep both coordinates strictly increasing
            if a > clean[-1][0] + 0.02 and b > clean[-1][1] + 0.02: clean.append((a, b))
        if clean[-1] != (dur, dur): clean[-1] = (dur, dur)
        # smooth the offset (anim - film) so playback speed changes gently
        xs = np.array([a for a, b in clean]); off = np.array([b - a for a, b in clean])
        grid = np.arange(0, dur + 1e-9, 0.05); d = np.interp(grid, xs, off)
        k = np.exp(-0.5 * (np.arange(-30, 31) * 0.05 / 0.35) ** 2); k /= k.sum()
        ds = np.convolve(np.pad(d, 30, mode="edge"), k, "valid")
        ds -= np.interp(grid, [0, dur], [ds[0], ds[-1]])  # pin both ends to zero offset
        g = grid[::2]; m = (g + ds[::2])
        pts = [[round(float(a), 3), round(float(b), 3)] for a, b in zip(g, m) if a < dur - 0.05]
        pts[0] = [0.0, 0.0]; pts.append([round(dur, 3), round(dur, 3)])
        out[sid] = pts
    return out

A = anchors()
def _interp(x, xs, ys):
    if x <= xs[0]: return ys[0] + (x - xs[0])
    for i in range(1, len(xs)):
        if x <= xs[i]: return ys[i - 1] + (ys[i] - ys[i - 1]) * (x - xs[i - 1]) / (xs[i] - xs[i - 1])
    return ys[-1] + (x - xs[-1])
def old_to_new(sid, t):
    p = A[sid]; return _interp(t, [b for a, b in p], [a for a, b in p])

if __name__ == "__main__":
    js = "/* Generated by scripts/build_warp.py — maps film time to the time the animation was authored at,\n   so on-screen beats land on the words of the current narration. */\n"
    js += "window.WARP = " + json.dumps(A) + ";\n"
    js += """HF.warp = function (id, t) {
  const p = (window.WARP || {})[id]; if (!p) return t;
  if (t <= p[0][0]) return t;
  for (let i = 1; i < p.length; i++) if (t <= p[i][0]) return p[i - 1][1] + (p[i][1] - p[i - 1][1]) * (t - p[i - 1][0]) / (p[i][0] - p[i - 1][0]);
  return t;
};
"""
    open(ROOT + "/video/lib/warp.js", "w").write(js)
    for k, v in A.items():
        sl = [(v[i][1] - v[i - 1][1]) / (v[i][0] - v[i - 1][0]) for i in range(1, len(v))]
        print(k, len(v), "anchors, speed range", round(min(sl), 2), "-", round(max(sl), 2))
