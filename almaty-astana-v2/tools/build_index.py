"""Generate index.html from tools/timeline.json so scene durations always follow the narration."""
import json, os
R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
T = json.load(open(f"{R}/tools/timeline.json")); tot = T["total"]
files = {"opening":"opening","map":"map","almaty":"almaty","astana":"astana","climate":"climate","life":"lifestyle","board":"board","finale":"finale"}
clips = "\n".join(f'  <div class="clip" id="scene-{s["id"]}" data-composition-id="sc-{ {"life":"life"}.get(s["id"], s["id"]) }" data-composition-src="compositions/{files[s["id"]]}.html" data-start="{s["start"]}" data-duration="{round(s["dur"]+0.0,3)}" data-track-index="1"></div>' for s in T["scenes"])
html = f'''<!doctype html>
<html lang="ru" data-resolution="portrait" data-fps="30">
<head><meta charset="UTF-8"/><meta name="viewport" content="width=1080, height=1920"/>
<title>Алматы vs Астана — два города, два мира (v2)</title>
<link rel="stylesheet" href="styles/theme.css"/><link rel="stylesheet" href="styles/panels.css"/>
<script src="vendor/gsap.min.js"></script>
<script src="lib/mapdata.js"></script><script src="lib/timeline.js"></script><script src="lib/subs.js"></script>
<script src="lib/kit.js"></script><script src="lib/tl.js"></script><script src="lib/ui.js"></script><script src="lib/hud.js"></script><script src="lib/landmarks.js"></script>
<script src="lib/aerial.js"></script><script src="lib/shots-almaty.js"></script><script src="lib/shots-astana.js"></script><script src="lib/shots-extra.js"></script><script src="lib/shots.js"></script><script src="lib/scene.js"></script><script src="lib/bgfx.js"></script>
</head>
<body>
<!-- GENERATED by tools/build_index.py — scene lengths follow the narration (tools/timeline.json). {tot:.1f} s total. -->
<div id="root" data-composition-id="main" data-start="0" data-duration="{tot}" data-width="1080" data-height="1920">
{clips}
  <div class="clip" id="subtitles" data-composition-id="sc-subs" data-composition-src="compositions/subtitles.html" data-start="0" data-duration="{tot}" data-track-index="3"></div>
  <div class="clip" id="transitions" data-composition-id="sc-trans" data-composition-src="compositions/transitions.html" data-start="0" data-duration="{tot}" data-track-index="4"></div>
  <audio id="vo" src="assets/vo/narration.wav" data-start="0" data-duration="{tot}" data-track-index="10" data-volume="1"></audio>
  <audio id="score" src="assets/audio/score.wav" data-start="0" data-duration="{tot}" data-track-index="11" data-volume="1"></audio>
</div>
<script>
window.__timelines=window.__timelines||{{}};
const tl=gsap.timeline({{paused:true}}); window.__timelines["main"]=tl; tl.seek(0);
</script></body></html>
'''
open(f"{R}/index.html", "w").write(html); print("index.html", tot)
