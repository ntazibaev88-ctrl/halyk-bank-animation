"""Assemble the film: timing.js (word clock for scenes), compositions/captions.html and index.html.
Run after tools/tts.py:  python3 tools/build.py"""
import json, os, re
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
W, H, FPS = 1080, 1920, 30
# scene id -> (duration, voiceover offset inside the scene)
# scene id -> (voiceover offset inside the scene, tail after the last word); the voice is the clock,
# so each scene lasts exactly as long as its narration needs
PLAN = [("s1", 1.2, 1.3), ("s2", 1.0, 1.4), ("s3", 1.0, 2.7), ("s4", 1.0, 1.4),
        ("s5", 1.0, 1.4), ("s6", 1.0, 1.5), ("s7", 1.0, 1.5), ("s8", 1.0, 4.6)]
GOLD = ["астана", "қазақстан", "тәуелсіздік", "болашақ", "болашағы", "1997", "ақмола", "бәйтерек", "ақорда",
        "хан", "шатыр", "expo", "мегаполис", "жүрегі", "өсіп", "халық", "экономикалық", "инвестиция",
        "туристер", "мәдени", "технологиялар", "жасыл", "арманы", "үміті", "қолымызда", "сәулеті", "ертеңгі"]
vo = {s["id"]: s for s in json.load(open(f"{ROOT}/tools/vo-words.json", encoding="utf-8"))}
SCENES = [(sid, round((off + vo[sid]["words"][-1]["end"] + tail) * 5 + 0.499) / 5, off) for sid, off, tail in PLAN]
# keep every scene file's clip slots equal to its scene length
for sid, dur, _ in SCENES:
    fp = f"{ROOT}/compositions/{sid}.html"
    if os.path.exists(fp):
        src = open(fp, encoding="utf-8").read()
        open(fp, "w", encoding="utf-8").write(re.sub(r'data-start="0" data-duration="[0-9.]+"', f'data-start="0" data-duration="{dur}"', src))
def r(x): return round(x + 1e-9, 3)

timing, t0, caps = {}, 0.0, []
for sid, dur, off in SCENES:
    disp, toks = [], vo[sid]["text"].split()
    for tk in toks:
        if tk == "—": disp[-1] += " —"
        else: disp.append(tk)
    words = vo[sid]["words"]
    assert len(disp) == len(words), sid
    timing[sid] = {"start": r(t0), "dur": dur, "vo": off,
                   "words": [{"w": re.sub(r"[^\w-]", "", d), "t": r(off + w["start"]), "e": r(off + w["end"])} for d, w in zip(disp, words)]}
    # caption groups
    grp = []
    def flush():
        global grp
        if grp: caps.append(grp); grp = []
    for i, (d, w) in enumerate(zip(disp, words)):
        nxt_len = sum(len(x[0]) + 1 for x in grp) + len(d)
        if grp and (len(grp) >= 5 or nxt_len > 34): flush()
        grp.append((d, t0 + off + w["start"], t0 + off + w["end"]))
        gap = (words[i + 1]["start"] - w["end"]) if i + 1 < len(words) else 9
        if re.search(r"[.!?]$", d) or gap > 0.3 or (d.endswith(",") and len(grp) >= 3): flush()
    flush()
    t0 += dur
# no one-word orphans: merge into the previous group when it fits on two lines, else borrow a word
i = 1
while i < len(caps):
    a, b = caps[i - 1], caps[i]
    if len(b) == 1 and b[0][1] - a[-1][2] < 0.3:
        if sum(len(x[0]) + 1 for x in a) + len(b[0][0]) <= 46: caps[i - 1] = a + b; del caps[i]; continue
        if len(a) >= 3: caps[i] = [a[-1]] + b; caps[i - 1] = a[:-1]
    i += 1
TOTAL = r(t0)
json.dump(timing, open(f"{ROOT}/tools/timing.json", "w", encoding="utf-8"), ensure_ascii=False, indent=1)
open(f"{ROOT}/assets/js/timing.js", "w", encoding="utf-8").write(
    "// generated by tools/build.py\nwindow.ASTANA_TIMING = " + json.dumps(timing, ensure_ascii=False) + ";\n")

# ---------- captions ----------
def is_gold(word):
    lw = word.lower()
    return any(lw.startswith(g) for g in GOLD)
rows, js = [], []
for i, g in enumerate(caps):
    start = max(0.1, g[0][1] - 0.06)
    end = g[-1][2] + 0.4
    if i + 1 < len(caps): end = min(end, caps[i + 1][0][1] - 0.08)
    spans = " ".join(f'<span class="{"g" if is_gold(d) else "w"}">{d}</span>' for d, _, _ in g)
    rows.append(f'    <div id="cap-{i}" class="clip cap" data-start="{r(start)}" data-duration="{r(end - start)}" '
                f'data-layout-allow-caption-zone><p id="cap-{i}-t" class="cap-t">{spans}</p></div>')
    js.append(f"[{i},{r(start)},{r(end)}]")
captions = f"""<template>
  <style>
    #root {{ position: absolute; inset: 0; pointer-events: none; }}
    .cap {{ position: absolute; left: 60px; width: 960px; top: 1140px; height: 200px; display: flex;
      align-items: center; justify-content: center; text-align: center; overflow: visible; }}
    .cap-t {{ margin: 0; display: inline-block; max-width: 940px; padding: 18px 34px 20px; border-radius: 30px;
      background: rgba(6, 17, 38, 0.72); box-shadow: 0 10px 40px rgba(3, 10, 24, 0.35);
      font-family: 'Astana Sans', sans-serif; font-weight: 800; font-size: 54px; line-height: 1.22;
      letter-spacing: -0.005em; color: #fff; opacity: 0; }}
    .cap-t .g {{ color: #F7C55A; }}
  </style>
  <div id="root" data-composition-id="captions" data-width="{W}" data-height="{H}">
{chr(10).join(rows)}
  </div>
  <script>
    (function () {{
      const tl = gsap.timeline({{ paused: true }});
      const groups = [{",".join(js)}];
      groups.forEach(function (g) {{
        const el = "#cap-" + g[0] + "-t";
        tl.fromTo(el, {{ opacity: 0, y: 16 }}, {{ opacity: 1, y: 0, duration: 0.2, ease: "power3.out" }}, g[1]);
        tl.to(el, {{ opacity: 0, y: -8, duration: 0.12, ease: "power2.in" }}, g[2] - 0.13);
      }});
      tl.set({{}}, {{}}, {TOTAL});
      window.__timelines["captions"] = tl;
    }})();
  </script>
</template>
"""
open(f"{ROOT}/compositions/captions.html", "w", encoding="utf-8").write(captions)

# ---------- index ----------
faces = []
for wgt in (500, 700, 800, 900):
    for sub, rng in (("latin", "U+0000-00FF,U+2013-2014,U+2018-201D,U+20B8"),
                     ("cyrillic", "U+0301,U+0400-045F,U+0490-0491,U+04B0-04B1,U+2116"),
                     ("cyrillic-ext", "U+0460-052F,U+1C80-1C8A,U+20B4,U+2DE0-2DFF,U+A640-A69F,U+FE2E-FE2F")):
        faces.append(f"@font-face {{ font-family: 'Astana Sans'; font-weight: {wgt}; font-style: normal; "
                     f"src: url('assets/fonts/montserrat-{sub}-{wgt}-normal.woff2') format('woff2'); unicode-range: {rng}; }}")
import subprocess
def adur(rel):
    return round(float(subprocess.check_output(["ffprobe","-v","0","-show_entries","format=duration","-of","csv=p=0",f"{ROOT}/{rel}"]).decode().strip()) - 0.02, 2)
hosts, audio, t0 = [], [], 0.0
SFX = {"s2": "whoosh.mp3", "s3": "whoosh-short.mp3", "s4": "whoosh-cinematic.mp3", "s5": "whoosh.mp3",
       "s6": "whoosh-short.mp3", "s7": "whoosh-cinematic.mp3", "s8": "whoosh.mp3"}
for i, (sid, dur, off) in enumerate(SCENES):
    if os.path.exists(f"{ROOT}/compositions/{sid}.html"): hosts.append(f'      <div id="{sid}" class="clip" data-composition-id="{sid}" data-composition-src="compositions/{sid}.html" '
                 f'data-start="{r(t0)}" data-duration="{dur}" data-track-index="1" data-track-kind="graphics" '
                 f'data-width="{W}" data-height="{H}" style="z-index:{i + 1}"></div>')
    audio.append(f'      <audio id="vo-{sid}" class="clip" src="assets/audio/vo-{sid}.mp3" data-start="{r(t0 + off)}" data-duration="{adur(f'assets/audio/vo-{sid}.mp3')}" '
                 f'data-track-index="3" data-volume="1"></audio>')
    if sid in SFX:
        audio.append(f'      <audio id="sfx-{sid}" class="clip" src="assets/audio/sfx/{SFX[sid]}" data-start="{r(t0 - 0.35)}" data-duration="{min(adur('assets/audio/sfx/' + SFX[sid]), 3.0)}" data-fade-out="0.4" '
                     f'data-track-index="{5 + i % 2}" data-volume="0.32"></audio>')
    t0 += dur
index = f"""<!doctype html>
<html lang="kk">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width={W}, height={H}" />
    <title>Астана — болашақтың қаласы</title>
    <script src="assets/js/gsap.min.js"></script>
    <script src="assets/js/timing.js"></script>
    <script src="assets/js/astana.js"></script>
    <style>
      {chr(10).join("      " + f for f in faces).strip()}
      * {{ margin: 0; padding: 0; box-sizing: border-box; }}
      html, body {{ margin: 0; width: {W}px; height: {H}px; overflow: hidden; background: #07142B; }}
      #root {{ position: relative; width: {W}px; height: {H}px; overflow: hidden; font-family: 'Astana Sans', sans-serif; }}
    </style>
    <link rel="stylesheet" href="assets/film.css" />
  </head>
  <body>
    <div id="root" data-composition-id="main" data-start="0" data-duration="{TOTAL}" data-fps="{FPS}" data-width="{W}" data-height="{H}">
{chr(10).join(hosts)}
      <div id="captions" class="clip" data-composition-id="captions" data-composition-src="compositions/captions.html"
        data-start="0" data-duration="{TOTAL}" data-track-index="2" data-track-kind="captions" data-width="{W}" data-height="{H}" style="z-index:50"></div>
{chr(10).join(audio)}
      <audio id="music" class="clip" src="assets/audio/music.mp3" data-start="0" data-duration="{TOTAL}" data-track-index="4" data-volume="0.3"></audio>
    </div>
    <script>
      window.__timelines = window.__timelines || {{}};
      (function () {{
        const tl = gsap.timeline({{ paused: true }});
        tl.set({{}}, {{}}, {TOTAL});
        window.__timelines["main"] = tl;
      }})();
    </script>
  </body>
</html>
"""
open(f"{ROOT}/index.html", "w", encoding="utf-8").write(index)
print("total", TOTAL, "captions", len(caps))
for g in caps: print(f"  {g[0][1]:7.2f}  " + " ".join(d for d, _, _ in g))
